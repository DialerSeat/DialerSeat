// =============================================================================
// scripts/gen-page-dates.mjs — writes lib/pageDates.ts from git history
// =============================================================================
// The sitemap stamped every URL with `new Date()`, so all 116 pages claimed to
// have changed at the moment the sitemap was requested. A lastmod that is
// always "now" carries no information, and Google says as much: it uses
// lastmod only when it is "consistently and verifiably accurate", and ignores
// it for a site where it is not. That throws away the one signal that tells a
// crawler which pages are worth re-fetching.
//
// This reads the real date instead: the latest commit touching the files a
// page renders from. A file with uncommitted edits counts as changed today,
// so running this before a commit stamps the pages that commit changes.
//
//   node scripts/gen-page-dates.mjs
//
// Run it whenever marketing pages change. It is deliberately a script and not
// a build step: Vercel clones shallowly, so `git log` at build time would
// report the deploy date for every file, which is the bug this replaces.
// =============================================================================

import { execSync } from 'node:child_process'
import { readdirSync, statSync, existsSync, writeFileSync } from 'node:fs'
import { join, relative, sep } from 'node:path'

const ROOT = process.cwd()
const APP = join(ROOT, 'app')

/** Route prefixes that are public marketing pages. Everything else is the app. */
const PUBLIC_PREFIXES = ['/', '/faq', '/vs', '/dialing-modes', '/data', '/tools', '/pricing', '/features', '/resources', '/about', '/status', '/terms', '/privacy']

/** Shared sources whose edits change the rendered content of a route family. */
const SHARED = {
  '/vs/': ['lib/competitors.ts', 'lib/competitorFeatures.ts', 'components/vs-competitor-view.tsx'],
  '/data/dialer-pricing': ['lib/competitors.ts'],
  '/pricing': ['lib/competitors.ts', 'lib/weeklyBilling.ts'],
  '/data/calling-rules-by-country': ['lib/countryRules.ts'],
}

const today = new Date().toISOString().slice(0, 10)
const dirty = new Set(
  execSync('git status --porcelain', { encoding: 'utf8' })
    .split('\n')
    .filter(Boolean)
    .map((l) => l.slice(3).trim().replace(/^"|"$/g, '').split(' -> ').pop().replaceAll('\\', '/')),
)

function lastChanged(file) {
  const rel = relative(ROOT, file).split(sep).join('/')
  if (!existsSync(file)) return null
  if ([...dirty].some((d) => rel === d || rel.startsWith(d.endsWith('/') ? d : d + '/'))) return today
  const out = execSync(`git log -1 --format=%cs -- "${rel}"`, { encoding: 'utf8' }).trim()
  return out || today
}

function walk(dir) {
  const found = []
  for (const name of readdirSync(dir)) {
    const full = join(dir, name)
    if (statSync(full).isDirectory()) found.push(...walk(full))
    else if (name === 'page.tsx') found.push(full)
  }
  return found
}

const dates = {}
for (const page of walk(APP)) {
  const dir = page.slice(0, -'page.tsx'.length)
  let route = '/' + relative(APP, dir).split(sep).filter(Boolean).join('/')
  if (route.includes('[')) continue // dynamic routes are dated by their generator below
  const isPublic = PUBLIC_PREFIXES.some((p) =>
    p === '/' ? route === '/' : route === p || route.startsWith(p + '/'))
  if (!isPublic) continue

  const sources = [page, join(dir, 'view.tsx')]
  for (const [prefix, files] of Object.entries(SHARED)) {
    if (route.startsWith(prefix) || route === prefix) sources.push(...files.map((f) => join(ROOT, f)))
  }
  const stamps = sources.map(lastChanged).filter(Boolean).sort()
  if (stamps.length) dates[route] = stamps[stamps.length - 1]
}

// Head-to-head pages all render from one template and the registry.
dates['/vs/[matchup]'] = [join(APP, 'vs', '[matchup]', 'page.tsx'), join(ROOT, 'lib/competitors.ts')]
  .map(lastChanged)
  .filter(Boolean)
  .sort()
  .pop()

const sorted = Object.fromEntries(Object.entries(dates).sort(([a], [b]) => a.localeCompare(b)))
const body = `// GENERATED by scripts/gen-page-dates.mjs — do not edit by hand.
// The date each public page last changed, read from git. Used by app/sitemap.ts
// for <lastmod>, and by pages that print an "Updated" line. Regenerate with:
//   node scripts/gen-page-dates.mjs

export const PAGE_DATES: Record<string, string> = ${JSON.stringify(sorted, null, 2)}

/** Latest date across every page: the fallback for a route missing above. */
export const SITE_UPDATED = '${Object.values(sorted).sort().pop()}'

/** The date a route last changed, as YYYY-MM-DD. */
export function pageDate(path: string): string {
  if (PAGE_DATES[path]) return PAGE_DATES[path]
  if (/^\\/vs\\/[a-z0-9-]+-vs-[a-z0-9-]+$/.test(path)) return PAGE_DATES['/vs/[matchup]'] ?? SITE_UPDATED
  return SITE_UPDATED
}
`
writeFileSync(join(ROOT, 'lib', 'pageDates.ts'), body)
console.log(`wrote lib/pageDates.ts: ${Object.keys(sorted).length} routes`)
